def t(key: str, **kw) -> str:
    ru, kk = MSG[key]
    return (kk if lang.get() == "kk" else ru).format(**kw)


def name(client_id: int, ru_name: str) -> str:
    return NAMES_KK.get(client_id, ru_name) if lang.get() == "kk" else ru_name


def reasons(items: list[dict]) -> list[dict]:
    """Тексты признаков в языке клиента, самые весомые первыми; баллы и коды не меняются."""
    out = []
    items = sorted(items, key=lambda r: -(r.get("points") or 0))
    for r in items:
        key = "reason." + r.get("code", "")
        out.append(r | {"text": t(key)} if key in MSG else r)
    return out
