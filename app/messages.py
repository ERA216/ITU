"""Проверка подозрительного сообщения: клиент вставляет текст из мессенджера, система узнаёт схему.

Правила, а не нейросеть: каждое совпадение видно клиенту, решение можно объяснить. Тексты на русском
и казахском. Сам текст сообщения нигде не сохраняется, в базу пишется только найденная схема.
"""
import re

# (шаблон, вес). Сильный признак (2) сам по себе узнаёт схему, слабые (1) — только вместе.
SCHEMES = {
    "mistaken": [
        (r"по ошибке|ошибочн\w*|ошибл[аи]сь?|ошибся|не туда перев\w*|случайно перев\w*", 2),
        (r"қате аудар\w*|қателесіп", 2),
        (r"верн(и|ите|уть)\w*|переведите обратно|отправьте обратно|қайтар\w*", 1),
        (r"на (другую|эту|мою|новую) карт\w*|на (этот|другой|мой) номер|картасына|нөміріне", 1),
    ],
    "safe_account": [
        (r"безопасн\w* сч[её]т\w*|резервн\w* сч[её]т\w*|защищенн\w* сч[её]т\w*|специальн\w* сч[её]т\w*", 2),
        (r"служб\w* безопасности|қауіпсіздік қызмет\w*|қауіпсіз шот\w*", 2),
        (r"(на ваше имя|на вас) (пытаются )?оформ\w* кредит|атыңызға несие", 2),
        (r"следовател\w*|нацбанк\w*|национальн\w* банк\w*|финмониторинг\w*|полици\w*|прокуратур\w*", 1),
        (r"подозрительн\w* операц\w*|сотрудник\w* банка|ваш\w* сч[её]т\w* (под угрозой|взлом\w*)", 1),
    ],
    "investment": [
        (r"\d+[.,]?\d* ?% (в|за) (день|сутки|неделю|месяц)|күніне \d+ ?%|\d+ ?% күніне", 2),
        (r"гарантированн\w* (доход|прибыль)|пассивн\w* доход\w*|кепілдендірілген табыс", 2),
        (r"инвест\w*|прибыл\w*|доход\w*|табыс\w*|пайда\w*", 1),
        (r"крипт\w*|биткоин\w*|usdt|бирж\w*|трейдинг\w*|брокер\w*|удвои\w*", 1),
    ],
    "job": [
        (r"принима\w* (переводы|платежи|деньги)|при[её]м платеж\w*|аударымдарды қабылда\w*", 2),
        (r"(переводить|перевести|переслать|пересылать|отправлять) (их |деньги )?дальше|әрі қарай аудар\w*", 2),
        (r"аренд\w* карт\w*|сдать карт\w*|сда[её]те карт\w*|оформ\w* карт\w* на себя", 2),
        (r"\d+ ?% (от суммы|от перевода|с суммы)|процент от (суммы|перевода)|сомадан \d+ ?%", 2),
        (r"подработк\w*|работа на дому|удал[её]нн\w* работ\w*|л[её]гк\w* заработ\w*|қосымша жұмыс\w*|оңай табыс\w*", 1),
    ],
}

# Общие тревожные признаки: сами по себе схему не называют, но говорят «будьте осторожны».
FLAGS = {
    "urgency": r"срочно|немедленно|прямо сейчас|пока не поздно|в течение \d+ (минут|час)\w*|тез арада|дереу|шұғыл",
    "secrecy": r"никому не (говорите|сообщайте|рассказывайте)|это конфиденциальн\w*|ешкімге айтпаңыз",
    "code": r"код из (смс|sms)|смс[- ]?код\w*|продиктуйте код|назовите код|cvv|cvc|кодты айтыңыз|кодты айт",
    "link": r"https?://\S+|bit\.ly/\S+|wa\.me/\S+|t\.me/\S+",
    "card": r"(?<!\d)(?:\d[ -]?){15}\d(?!\d)",
    "remote": r"anydesk|rustdesk|teamviewer|(скачайте|установите) приложение|қосымшаны орнатыңыз",
}


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text.lower().replace("ё", "е"))


def check(text: str) -> dict:
    """Какая схема похожа на этот текст, что именно совпало и какие есть тревожные признаки."""
    t = _norm(text)
    scores, matched = {}, {}
    for scheme, rules in SCHEMES.items():
        for pattern, weight in rules:
            found = [m.group(0) for m in re.finditer(pattern, t)]
            if found:
                scores[scheme] = scores.get(scheme, 0) + weight
                matched.setdefault(scheme, []).extend(found)
    flags = [code for code, pattern in FLAGS.items() if re.search(pattern, t)]
    best = max(scores, key=lambda k: (scores[k], -list(SCHEMES).index(k)), default=None)
    if best and scores[best] >= 2:
        verdict = "danger"
    else:
        best, verdict = None, "caution" if flags else "none"
    fragments = list(dict.fromkeys(matched.get(best, [])))[:6] if best else []
    return {"scheme": best, "verdict": verdict, "matched": fragments, "flags": flags,
            "score": scores.get(best, 0) if best else 0}
